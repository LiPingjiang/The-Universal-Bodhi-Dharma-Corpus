def gen_terms(terms_list):
    return "\n".join(f"| {s} | {c} | {e} |" for s, c, e in terms_list)


def gen_blockquote(text):
    """將多行文本逐行加上 '> ' 前綴，使頌文換行在 Markdown 中得以保留。"""
    return "\n".join("> " + line.strip() for line in text.strip().split("\n"))


def main():
    n_verbatim = n_summary = n_skip = 0
    for dirname, (level, orig, trans, q1, q2, terms, source) in CONTENTS.items():
        filepath = os.path.join(BASE, dirname, "原文.md")
        if not os.path.exists(filepath):
            print(f"[跳過] {dirname} — 檔案不存在")
            n_skip += 1
            continue

        title = dirname.split("_", 1)[1] if "_" in dirname else dirname
        tpl = TEMPLATE_VERBATIM if level == VERBATIM else TEMPLATE_SUMMARY
        content = tpl.format(
            title=title,
            original=gen_blockquote(orig),
            translation=trans,
            quote1=q1,
            quote2=q2,
            terms=gen_terms(terms),
            source=source,
        )
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

        if level == VERBATIM:
            n_verbatim += 1
            print(f"[確引] {dirname}")
        else:
            n_summary += 1
            print(f"[義述] {dirname}")

    print(f"\n共處理 {n_verbatim + n_summary} 個文件"
          f"（確引 {n_verbatim}、義述待覈 {n_summary}、跳過 {n_skip}）")


if __name__ == "__main__":
    main()
